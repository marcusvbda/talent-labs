import type {
    ISODateTime,
    JobDetail,
    JobLanguage,
    Seniority,
} from '../../../types/contracts';
import { companyByName } from './companies';
import { daysAgo, minutesAgoToday } from './time';

// One array serves both the list and the detail. Ids are stable (1..60).
// Rows 1-20 are "collected today": firstSeenAt comes from minutesAgoToday,
// which clamps to the minutes elapsed since local midnight, so they always
// fall inside today. Rows 21-60 were first seen 1..13 days ago.

const SOURCES = [
    'RemoteOK',
    'WeWorkRemotely',
    'Greenhouse',
    'Lever',
    'Workable',
] as const;

const EMPLOYMENT: Record<JobLanguage, { full: string; intern: string }> = {
    en: { full: 'Full-time', intern: 'Internship' },
    pt: { full: 'Tempo integral', intern: 'Estágio' },
};

type Seen = { firstSeenAt: ISODateTime; collectedToday: boolean };

// Seen minutes ago, today.
const m = (minutes: number): Seen => ({
    firstSeenAt: minutesAgoToday(minutes),
    collectedToday: true,
});

// Seen days ago (1..13), not today.
const d = (days: number): Seen => ({
    firstSeenAt: daysAgo(days),
    collectedToday: false,
});

type Extra = { hybridRemote?: boolean; noPublishedAt?: boolean };

const job = (
    id: number,
    companyName: string,
    language: JobLanguage,
    seniority: Seniority,
    title: string,
    stack: string[],
    summary: string,
    department: string | null,
    seen: Seen,
    extra: Extra = {},
): JobDetail => {
    const company = companyByName(companyName);
    const remote = company.isRemote || extra.hybridRemote === true;
    const cityText = company.city ?? 'Remote';
    const location = company.isRemote ? cityText : company.city;
    const ageDays = seen.collectedToday
        ? 1
        : Math.round(
              (Date.now() - new Date(seen.firstSeenAt).getTime()) / 86_400_000,
          ) + 1;

    return {
        id,
        company: {
            id: company.id,
            name: company.name,
            initials: company.initials,
        },
        title,
        location,
        isRemote: remote,
        language,
        seniority,
        stack,
        summary,
        ...seen,
        locations: company.isRemote
            ? [cityText]
            : remote
              ? [cityText, 'Remote']
              : [cityText],
        employmentType:
            seniority === 'intern'
                ? EMPLOYMENT[language].intern
                : EMPLOYMENT[language].full,
        department,
        publishedAt: extra.noPublishedAt ? null : daysAgo(ageDays),
        sourceLabel: SOURCES[id % SOURCES.length],
    };
};

